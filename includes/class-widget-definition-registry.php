	/**
	 * Gets AI-authorable content setting rules for a widget.
	 *
	 * @return array<string,array<string,mixed>>
	 */
	public function content_setting_rules( string $widget_name ): array {
		$definition = $this->get_definition( $widget_name );

		return is_array( $definition ) && is_array( $definition['content_settings'] ?? null ) ? $definition['content_settings'] : array();
	}

	/**
	 * Gets a public-safe definition row.
	 *
	 * @return array<string,mixed>|null
	 */
	public function public_definition( string $widget_name ): ?array {
		$definition = $this->get_definition( $widget_name );

		return is_array( $definition ) ? $this->sanitize_definition( $definition ) : null;
	}

	/**
	 * Gets public definition rows with current Elementor detection state.
	 *
	 * @param array<int,array<string,mixed>> $widgets Current resolved widgets.
	 * @return array<int,array<string,mixed>>
	 */
	public function runtime_rows( array $widgets, Permission_Manager $permission_manager ): array {
		$widget_map = $this->index_widgets( $widgets );
		$rows       = array();

		foreach ( $this->list_definitions() as $widget_name => $definition ) {
			$widget   = $widget_map[ $widget_name ] ?? null;
			if ( null === $widget && 'container' === $widget_name && ! empty( $widgets ) ) {
				$widget = array(
					'name'            => 'container',
					'title'           => __( 'Container', 'ai-builder-connector' ),
					'categories'      => array( 'layout' ),
					'class_name'      => '',
					'source_slug'     => Addon_Detector::ELEMENTOR_CORE,
					'source_name'     => __( 'Elementor Core', 'ai-builder-connector' ),
					'review_required' => false,
				);
			}

			$detected = is_array( $widget );
			$allowed  = $detected && ( 'container' === $widget_name ? $permission_manager->is_addon_allowed( Addon_Detector::ELEMENTOR_CORE ) : $permission_manager->is_widget_allowed( $widget ) );

			$row = $this->sanitize_definition( $definition );
			$row['detected']       = $detected;
			$row['allowed']        = $allowed;
			$row['runtime_status'] = $this->runtime_status( $row, $widget, $allowed );
			$row['class_name']     = is_array( $widget ) ? sanitize_text_field( (string) ( $widget['class_name'] ?? '' ) ) : '';
			$row['categories']     = is_array( $widget ) ? array_values( array_map( 'sanitize_text_field', (array) ( $widget['categories'] ?? array() ) ) ) : array();

			$rows[] = $row;
		}

		return $rows;
	}

	/**
	 * Builds one definition.
	 *
	 * @param array<int,string>   $required Required setting keys.
	 * @param array<int,string>   $supported Supported setting keys.
	 * @param array<string,mixed> $defaults Default settings.
	 * @param array<string,array<string,mixed>> $content_settings AI-authorable content rules.
	 * @return array<string,mixed>
	 */
	private function definition( string $identifier, string $title, array $required, array $supported, array $defaults, string $limitations, array $content_settings = array() ): array {
		return array(
			'identifier'              => sanitize_text_field( $identifier ),
			'title'                   => sanitize_text_field( $title ),
			'source_plugin'           => Addon_Detector::ELEMENTOR_CORE,
			'support_status'          => self::STATUS_VERIFIED,
			'required_settings'       => array_values( array_map( 'sanitize_key', $required ) ),
			'supported_settings'      => array_values( array_map( 'sanitize_key', $supported ) ),
			'default_settings'        => $defaults,
			'content_settings'        => $content_settings,
			'validation_rules'        => array(
				'registered_widget_required',
				'addon_must_be_allowed',
				'widget_must_be_allowed',
				'unsupported_settings_rejected',
				'required_settings_present',
			),
			'responsive_capabilities' => array(
				'desktop',
				'tablet',
				'mobile',
			),
			'tested_elementor_versions' => self::TESTED_ELEMENTOR_VERSIONS,
			'known_limitations'         => sanitize_text_field( $limitations ),
		);
	}

	/**
	 * Sanitizes a definition for admin and MCP responses.
	 *
	 * @param array<string,mixed> $definition Raw definition.
	 * @return array<string,mixed>
	 */
	private function sanitize_definition( array $definition ): array {
		return array(
			'identifier'                => sanitize_text_field( (string) ( $definition['identifier'] ?? '' ) ),
			'title'                     => sanitize_text_field( (string) ( $definition['title'] ?? '' ) ),
			'source_plugin'             => sanitize_key( (string) ( $definition['source_plugin'] ?? '' ) ),
			'support_status'            => sanitize_key( (string) ( $definition['support_status'] ?? self::STATUS_UNSUPPORTED ) ),
			'required_settings'         => array_values( array_map( 'sanitize_key', (array) ( $definition['required_settings'] ?? array() ) ) ),
			'supported_settings'        => array_values( array_map( 'sanitize_key', (array) ( $definition['supported_settings'] ?? array() ) ) ),
			'default_settings'          => $definition['default_settings'] ?? array(),
			'ai_content_settings'       => $this->sanitize_content_settings( (array) ( $definition['content_settings'] ?? array() ) ),
			'validation_rules'          => array_values( array_map( 'sanitize_key', (array) ( $definition['validation_rules'] ?? array() ) ) ),
			'responsive_capabilities'   => array_values( array_map( 'sanitize_key', (array) ( $definition['responsive_capabilities'] ?? array() ) ) ),
			'tested_elementor_versions' => array_values( array_map( 'sanitize_text_field', (array) ( $definition['tested_elementor_versions'] ?? array() ) ) ),
			'known_limitations'         => sanitize_text_field( (string) ( $definition['known_limitations'] ?? '' ) ),
		);
	}

	/**
	 * Sanitizes content setting rules for public responses.
	 *
	 * @param array<string,mixed> $content_settings Raw content rules.
	 * @return array<string,array<string,mixed>>
	 */
	private function sanitize_content_settings( array $content_settings ): array {
		$sanitized = array();

		foreach ( $content_settings as $key => $rule ) {
			$key = sanitize_key( (string) $key );

			if ( '' === $key || ! is_array( $rule ) ) {
				continue;
			}

			$row = array( 'type' => sanitize_key( (string) ( $rule['type'] ?? '' ) ) );

			if ( isset( $rule['choices'] ) && is_array( $rule['choices'] ) ) {
				$row['choices'] = array_values( array_map( 'sanitize_text_field', array_map( 'strval', $rule['choices'] ) ) );
			}

			$sanitized[ $key ] = $row;
		}

		return $sanitized;
	}

	/**
	 * Gets runtime status for a definition row.
	 *
	 * @param array<string,mixed>      $definition Public definition row.
	 * @param array<string,mixed>|null $widget Runtime widget row.
	 */
	private function runtime_status( array $definition, ?array $widget, bool $allowed ): string {
		if ( null === $widget ) {
			return self::STATUS_UNSUPPORTED;
		}

		if ( ! empty( $widget['review_required'] ) ) {
			return self::STATUS_NEEDS_REVIEW;
		}

		if ( self::STATUS_VERIFIED === (string) ( $definition['support_status'] ?? '' ) && $allowed ) {
			return self::STATUS_VERIFIED;
		}

		if ( $allowed ) {
			return self::STATUS_ALLOWED;
		}

		return self::STATUS_DETECTED;
	}

	/**
	 * Indexes runtime widgets by internal name.
	 *
	 * @param array<int,array<string,mixed>> $widgets Runtime widget rows.
	 * @return array<string,array<string,mixed>>
	 */
	private function index_widgets( array $widgets ): array {
		$map = array();

		foreach ( $widgets as $widget ) {
			$name = sanitize_text_field( (string) ( $widget['name'] ?? '' ) );

			if ( '' !== $name ) {
				$map[ $name ] = $widget;
			}
		}

		return $map;
	}
