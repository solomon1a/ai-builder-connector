	/**
	 * Gets one widget definition.
	 *
	 * @return array<string,mixed>|null
	 */
	public function get_definition( string $widget_name ): ?array {
		$definitions = $this->list_definitions();
		$widget_name = sanitize_text_field( $widget_name );

		if ( isset( $definitions[ $widget_name ] ) ) {
			return $definitions[ $widget_name ];
		}

		return $this->introspected_definition( $widget_name );
	}

	/**
	 * Gets an auto-introspected definition for an addon widget, cached per request.
	 *
	 * Only used when a widget is not in the hand-verified pack. The allowlist and
	 * source checks that gate widget usage run independently in the validator and
	 * plan builder, so providing a definition here never bypasses permissions.
	 *
	 * @return array<string,mixed>|null
	 */
	private function introspected_definition( string $widget_name ): ?array {
		if ( null === $this->introspector ) {
			return null;
		}

		if ( array_key_exists( $widget_name, $this->introspection_cache ) ) {
			$cached = $this->introspection_cache[ $widget_name ];

			return false === $cached ? null : $cached;
		}

		$definition = $this->introspector->build_definition( $widget_name );

		$this->introspection_cache[ $widget_name ] = is_array( $definition ) ? $definition : false;

		return is_array( $definition ) ? $definition : null;
	}

	/**
	 * Gets safe supported setting keys for a widget.
	 *
	 * @return array<int,string>
	 */
	public function supported_setting_keys( string $widget_name ): array {
		$definition = $this->get_definition( $widget_name );

		return is_array( $definition ) ? (array) $definition['supported_settings'] : array();
	}

	/**
	 * Gets required setting keys for a widget.
	 *
	 * @return array<int,string>
	 */
	public function required_setting_keys( string $widget_name ): array {
		$definition = $this->get_definition( $widget_name );

		return is_array( $definition ) ? (array) $definition['required_settings'] : array();
	}

	/**
	 * Gets default settings for a widget.
	 *
	 * @return array<string,mixed>
	 */
	public function default_settings( string $widget_name ): array {
		$definition = $this->get_definition( $widget_name );

		return is_array( $definition ) ? (array) $definition['default_settings'] : array();
